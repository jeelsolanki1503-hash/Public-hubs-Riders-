const DICTS = { en, hi, mr };

export function contentLang() {
  const l = store.settings().lang || 'en';
  return DICTS[l] ? l : 'en';
}

export function speechLang() {
  const l = LANGUAGES.find((x) => x.id === contentLang());
  return l ? l.speech : 'en-IN';
}

export function t(key, vars) {
  const dict = DICTS[contentLang()];
  let s = dict[key] ?? en[key];
  if (s === undefined) {
    console.warn(`[i18n] missing key "${key}"`);
    return key;
  }
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  }
  return s;
}
